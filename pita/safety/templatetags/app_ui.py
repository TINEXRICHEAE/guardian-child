@register.simple_tag
def icon(name, size=20, cls=''):
    paths = _ICONS.get(name, '')
    return format_html(
        '<svg class="icon {}" width="{}" height="{}" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
        'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">{}</svg>',
        cls, size, size, mark_safe(paths))


_HEADINGS = {
    'high': 'Stop: this looks high risk',
    'suspicious': 'Some warning signs were found',
    'low': 'Low observed risk',
    'unable_to_verify': 'We could not check this yet',
}
_MODE_LABELS = {
    'live': 'Checked by Guardian AI',
    'cloud-dev': 'Checked with cloud AI (development)',
    'rules-only': 'Checked with safety rules only (AI unavailable)',
    'demo': 'Sample demonstration',
    'unable_to_verify': 'Checking unavailable',
}


@register.filter
def risk_heading(level):
    return _HEADINGS.get(level, _HEADINGS['unable_to_verify'])


@register.filter
def mode_label(mode):
    return _MODE_LABELS.get(mode, mode)


