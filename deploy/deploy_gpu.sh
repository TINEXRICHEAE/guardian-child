#!/usr/bin/env bash
# Deploy Guardian's web app to the Testbed GPU machine, which serves it publicly (plan.md §20).
#
#   bash deploy/deploy_gpu.sh              # update code, migrate, restart
#   bash deploy/deploy_gpu.sh --with-data  # also copy this laptop's database contents (first deploy)
#
# Needs the SSH key in ~/.ssh/hackathon_ed25519 (override with GUARDIAN_GPU_KEY / GUARDIAN_GPU_HOST).
# Secrets come from pita/.env on this laptop and are never committed; the server keeps its own secret key.
set -euo pipefail
cd "$(dirname "$0")/.."

KEY=${GUARDIAN_GPU_KEY:-$HOME/.ssh/hackathon_ed25519}
HOST=${GUARDIAN_GPU_HOST:-hackathon@137.63.190.11}
PUBLIC_HOST=${GUARDIAN_PUBLIC_HOST:-137-63-190-11.sslip.io}
PUBLIC_IP=${GUARDIAN_PUBLIC_IP:-137.63.190.11}
SITE="https://$PUBLIC_HOST"
SSH=(ssh -i "$KEY" -o BatchMode=yes -o ConnectTimeout=20 "$HOST")
SCP=(scp -q -i "$KEY" -o BatchMode=yes -o ConnectTimeout=20)
WSL=(wsl -d Ubuntu-24.04 --)
UP_WIN='C:\Users\hackathon\guardian-upload'
UP_WSL=/mnt/c/Users/hackathon/guardian-upload
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

echo "1/6 packing code"
git ls-files -co --exclude-standard -- pita deploy requirements.txt \
  | grep -vE '(^|/)\.env$|\.sqlite3$|(^|/)media/|staticfiles/' > "$WORK/files"
tar -czf "$WORK/release.tar.gz" -T "$WORK/files"

echo "2/6 building the server settings from pita/.env"
EXISTING_KEY=$("${SSH[@]}" "${WSL[@]}" cat /home/hackathon/guardian-web/app/pita/.env 2>/dev/null | tr -d '\r' | sed -n 's/^DJANGO_SECRET_KEY=//p' | head -1 || true)
python3 - "$WORK/server.env" "$SITE" "$PUBLIC_HOST" "$PUBLIC_IP" "$EXISTING_KEY" <<'PY'
import secrets, sys
out, site, host, ip, key = sys.argv[1:6]
lines = [l.rstrip('\n') for l in open('pita/.env', encoding='utf-8')]
override = {
    'DEBUG': 'False',
    'DJANGO_SECRET_KEY': key or secrets.token_urlsafe(50),
    'SITE_URL': site,
    'ALLOWED_HOST': f'{host},{ip}',
    'CSRF_TRUSTED_ORIGINS': site,
    'GUARDIAN_BEHIND_PROXY': 'True',
    'DATABASE_URL': 'sqlite:////home/hackathon/guardian-web/data/guardian.sqlite3',
    'GUARDIAN_MEDIA_ROOT': '/home/hackathon/guardian-web/data/media',
    'GUARDIAN_SERVE_MEDIA': 'True',
    'GUARDIAN_AI_URL': 'http://127.0.0.1:8000',      # same machine: no SSH tunnel
}
seen, result = set(), []
for line in lines:
    k = line.split('=', 1)[0].strip()
    if line.strip().startswith('#') or '=' not in line:
        result.append(line); continue
    if k in override:
        result.append(f'{k}={override[k]}'); seen.add(k)
    else:
        result.append(line)
result += [f'{k}={v}' for k, v in override.items() if k not in seen]
open(out, 'w', encoding='utf-8').write('# Generated by deploy/deploy_gpu.sh. Do not commit.\n' + '\n'.join(result) + '\n')
PY

DATA_ARG=""
if [ "${1:-}" = "--with-data" ]; then
    echo "3/6 exporting this laptop's data"
    (cd pita && ../.venv/bin/python manage.py dumpdata --natural-foreign \
        --exclude contenttypes --exclude auth.permission --exclude sessions --exclude admin.logentry \
        -o "$WORK/data.json")
    DATA_ARG="$UP_WSL/data.json"
else
    echo "3/6 keeping the server's data"
fi

echo "4/6 uploading"
"${SSH[@]}" "if not exist $UP_WIN mkdir $UP_WIN & if not exist C:\\Users\\hackathon\\guardian-web mkdir C:\\Users\\hackathon\\guardian-web" >/dev/null
"${SCP[@]}" "$WORK/release.tar.gz" "$WORK/server.env" "$HOST:guardian-upload/"
[ -n "$DATA_ARG" ] && "${SCP[@]}" "$WORK/data.json" "$HOST:guardian-upload/"
"${SCP[@]}" deploy/gpu/Caddyfile "$HOST:guardian-web/Caddyfile"
"${SCP[@]}" guardian-ai/scripts/start_all.sh "$HOST:guardian-upload/start_all.sh"

echo "5/6 making sure Caddy is installed on Windows"
"${SSH[@]}" "if not exist C:\\Users\\hackathon\\guardian-web\\caddy.exe (cd /d C:\\Users\\hackathon\\guardian-web && curl.exe -sSL -o caddy.zip https://github.com/caddyserver/caddy/releases/download/v2.8.4/caddy_2.8.4_windows_amd64.zip && tar -xf caddy.zip caddy.exe && del caddy.zip)"

echo "6/6 installing and restarting on the server"
cat > "$WORK/run_setup.sh" <<SH
set -e
cp $UP_WSL/start_all.sh /home/hackathon/guardian-ai/scripts/start_all.sh
rm -rf /tmp/guardian-setup && mkdir -p /tmp/guardian-setup
tar -xzf $UP_WSL/release.tar.gz -C /tmp/guardian-setup deploy/gpu/server_setup.sh
bash /tmp/guardian-setup/deploy/gpu/server_setup.sh $UP_WSL/release.tar.gz $UP_WSL/server.env $DATA_ARG
SH
"${SCP[@]}" "$WORK/run_setup.sh" "$HOST:guardian-upload/run_setup.sh"
"${SSH[@]}" "${WSL[@]}" bash $UP_WSL/run_setup.sh
"${SSH[@]}" "del /q $UP_WIN\\server.env $UP_WIN\\data.json $UP_WIN\\release.tar.gz $UP_WIN\\run_setup.sh 2>nul" || true

echo
echo "Checking $SITE ..."
sleep 3
curl -s -m 20 -o /dev/null -w "public site: HTTP %{http_code}\n" "$SITE/" || echo "public site did not answer yet (certificate may still be issuing; try again in a minute)"
